USE DATABASE ENTERPRISE_BANKING;
USE SCHEMA GOLD;

TRUNCATE TABLE MART_CUSTOMER_360;

-- DESC TABLE CORE.DIM_CUSTOMER;

INSERT INTO MART_CUSTOMER_360
(

CUSTOMER_KEY,
CUSTOMER_ID,
FULL_NAME,
EMAIL,
PHONE_NUMBER,
CITY,
STATE,
CUSTOMER_PROFILE,
CUSTOMER_STATUS,
TOTAL_TRANSACTIONS,
TOTAL_DEPOSITS,
TOTAL_WITHDRAWALS,
TOTAL_LOANS,
OUTSTANDING_LOAN_BALANCE,
TOTAL_CREDIT_CARDS,
TOTAL_CREDIT_LIMIT,
CREDIT_BALANCE,
AVAILABLE_CREDIT,
FRAUD_CASES,
MAX_RISK_SCORE,
LAST_TRANSACTION_DATE

)

WITH TRANSACTION_SUMMARY AS
(

SELECT

CUSTOMER_KEY,

COUNT(*) TOTAL_TRANSACTIONS,

SUM(
CASE
WHEN TRANSACTION_DIRECTION='CREDIT'
THEN TRANSACTION_AMOUNT
ELSE 0
END
) TOTAL_DEPOSITS,

SUM(
CASE
WHEN TRANSACTION_DIRECTION='DEBIT'
THEN TRANSACTION_AMOUNT
ELSE 0
END
) TOTAL_WITHDRAWALS,

MAX(TRANSACTION_TIMESTAMP)
LAST_TRANSACTION_DATE

FROM CORE.FACT_TRANSACTIONS

GROUP BY CUSTOMER_KEY

),

LOAN_SUMMARY AS
(

SELECT

CUSTOMER_KEY,

COUNT(*) TOTAL_LOANS,

SUM(OUTSTANDING_BALANCE)
OUTSTANDING_LOAN_BALANCE

FROM CORE.FACT_LOANS

GROUP BY CUSTOMER_KEY

),

CARD_SUMMARY AS
(

SELECT

CUSTOMER_KEY,

COUNT(*) TOTAL_CREDIT_CARDS,

SUM(CREDIT_LIMIT)
TOTAL_CREDIT_LIMIT,

SUM(CURRENT_BALANCE)
CREDIT_BALANCE,

SUM(AVAILABLE_CREDIT)
AVAILABLE_CREDIT

FROM CORE.FACT_CREDIT_CARDS

GROUP BY CUSTOMER_KEY

),

FRAUD_SUMMARY AS
(

SELECT

CUSTOMER_KEY,

COUNT(*) FRAUD_CASES,

MAX(RISK_SCORE)
MAX_RISK_SCORE

FROM CORE.FACT_FRAUD

GROUP BY CUSTOMER_KEY

)

SELECT

C.CUSTOMER_KEY,

C.CUSTOMER_ID,

CONCAT(C.FIRST_NAME, ' ', C.LAST_NAME) AS FULL_NAME,

C.EMAIL,

C.PHONE_NUMBER,

C.CITY,

C.STATE,

C.CUSTOMER_PROFILE,

C.CUSTOMER_STATUS,

COALESCE(T.TOTAL_TRANSACTIONS,0),

COALESCE(T.TOTAL_DEPOSITS,0),

COALESCE(T.TOTAL_WITHDRAWALS,0),

COALESCE(L.TOTAL_LOANS,0),

COALESCE(L.OUTSTANDING_LOAN_BALANCE,0),

COALESCE(CC.TOTAL_CREDIT_CARDS,0),

COALESCE(CC.TOTAL_CREDIT_LIMIT,0),

COALESCE(CC.CREDIT_BALANCE,0),

COALESCE(CC.AVAILABLE_CREDIT,0),

COALESCE(F.FRAUD_CASES,0),

COALESCE(F.MAX_RISK_SCORE,0),

T.LAST_TRANSACTION_DATE

FROM CORE.DIM_CUSTOMER C

LEFT JOIN TRANSACTION_SUMMARY T

ON C.CUSTOMER_KEY=T.CUSTOMER_KEY

LEFT JOIN LOAN_SUMMARY L

ON C.CUSTOMER_KEY=L.CUSTOMER_KEY

LEFT JOIN CARD_SUMMARY CC

ON C.CUSTOMER_KEY=CC.CUSTOMER_KEY

LEFT JOIN FRAUD_SUMMARY F

ON C.CUSTOMER_KEY=F.CUSTOMER_KEY

WHERE C.IS_CURRENT=TRUE;