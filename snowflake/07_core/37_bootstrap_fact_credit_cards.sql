USE DATABASE ENTERPRISE_BANKING;
USE SCHEMA CORE;

INSERT INTO FACT_CREDIT_CARDS
(
    CARD_ID,

    CUSTOMER_KEY,
    CUSTOMER_ID,

    ACCOUNT_KEY,
    ACCOUNT_ID,

    BRANCH_KEY,
    BRANCH_ID,

    DATE_KEY,

    CARD_PRODUCT,
    CARD_STATUS,

    CREDIT_LIMIT,
    CURRENT_BALANCE,
    AVAILABLE_CREDIT,

    APR,

    ISSUED_DATE,
    EXPIRATION_DATE,

    CURRENCY_CODE,

    SOURCE_FILE,

    RAW_LOAD_TIMESTAMP
)

SELECT

    C.CARD_ID,

    DC.CUSTOMER_KEY,
    C.CUSTOMER_ID,

    DA.ACCOUNT_KEY,
    C.ACCOUNT_ID,

    DB.BRANCH_KEY,
    C.BRANCH_ID,

    DD.DATE_KEY,

    C.CARD_PRODUCT,

    C.CARD_STATUS,

    C.CREDIT_LIMIT,

    C.CURRENT_BALANCE,

    C.AVAILABLE_CREDIT,

    C.APR,

    C.ISSUED_DATE,

    C.EXPIRATION_DATE,

    C.CURRENCY_CODE,

    C.SOURCE_FILE,

    C.LOAD_TIMESTAMP

FROM STAGING.STG_CREDIT_CARDS C

LEFT JOIN CORE.DIM_CUSTOMER DC
       ON C.CUSTOMER_ID = DC.CUSTOMER_ID
      AND DC.IS_CURRENT = TRUE

LEFT JOIN CORE.DIM_ACCOUNT DA
       ON C.ACCOUNT_ID = DA.ACCOUNT_ID
      AND DA.IS_CURRENT = TRUE

LEFT JOIN CORE.DIM_BRANCH DB
       ON C.BRANCH_ID = DB.BRANCH_ID

LEFT JOIN CORE.DIM_DATE DD
       ON DD.FULL_DATE = C.ISSUED_DATE;