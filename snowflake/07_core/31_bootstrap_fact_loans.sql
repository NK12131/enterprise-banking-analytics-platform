USE DATABASE ENTERPRISE_BANKING;
USE SCHEMA CORE;

INSERT INTO FACT_LOANS
(
    LOAN_ID,

    CUSTOMER_KEY,
    CUSTOMER_ID,

    ACCOUNT_KEY,
    ACCOUNT_ID,

    BRANCH_KEY,
    BRANCH_ID,

    DATE_KEY,

    LOAN_TYPE,
    LOAN_STATUS,

    ORIGINAL_PRINCIPAL,
    OUTSTANDING_BALANCE,

    INTEREST_RATE,

    TERM_MONTHS,

    MONTHLY_PAYMENT,

    CURRENCY_CODE,

    ORIGINATION_DATE,
    MATURITY_DATE,

    SOURCE_FILE,

    RAW_LOAD_TIMESTAMP
)

SELECT

    L.LOAN_ID,

    DC.CUSTOMER_KEY,
    L.CUSTOMER_ID,

    DA.ACCOUNT_KEY,
    L.ACCOUNT_ID,

    DB.BRANCH_KEY,
    L.BRANCH_ID,

    DD.DATE_KEY,

    L.LOAN_TYPE,

    L.LOAN_STATUS,

    L.ORIGINAL_PRINCIPAL,

    L.OUTSTANDING_BALANCE,

    L.INTEREST_RATE,

    L.TERM_MONTHS,

    L.MONTHLY_PAYMENT,

    L.CURRENCY_CODE,

    L.ORIGINATION_DATE,

    L.MATURITY_DATE,

    L.SOURCE_FILE,

    L.LOAD_TIMESTAMP

FROM STAGING.STG_LOANS L

LEFT JOIN CORE.DIM_CUSTOMER DC

ON L.CUSTOMER_ID = DC.CUSTOMER_ID

AND DC.IS_CURRENT = TRUE

LEFT JOIN CORE.DIM_ACCOUNT DA

ON L.ACCOUNT_ID = DA.ACCOUNT_ID

AND DA.IS_CURRENT = TRUE

LEFT JOIN CORE.DIM_BRANCH DB

ON L.BRANCH_ID = DB.BRANCH_ID

LEFT JOIN CORE.DIM_DATE DD

ON DD.FULL_DATE = L.ORIGINATION_DATE;