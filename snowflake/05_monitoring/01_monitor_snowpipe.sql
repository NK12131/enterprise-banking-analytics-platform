USE DATABASE ENTERPRISE_BANKING;

USE SCHEMA RAW;


SELECT
    SYSTEM$PIPE_STATUS(
        'PIPE_BRANCHES'
    );


SELECT
    SYSTEM$PIPE_STATUS(
        'PIPE_CUSTOMERS'
    );


SELECT
    SYSTEM$PIPE_STATUS(
        'PIPE_TRANSACTIONS'
    );


SELECT
    TABLE_NAME,
    FILE_NAME,
    STATUS,
    ROW_COUNT,
    ROW_PARSED,
    FIRST_ERROR_MESSAGE,
    LAST_LOAD_TIME
FROM TABLE(
    INFORMATION_SCHEMA.COPY_HISTORY(
        TABLE_NAME => 'RAW_TRANSACTIONS',
        START_TIME => DATEADD(
            'HOUR',
            -24,
            CURRENT_TIMESTAMP()
        )
    )
)
ORDER BY LAST_LOAD_TIME DESC;


SELECT
    'BRANCHES' AS DATASET,
    COUNT(*) AS ROW_COUNT
FROM RAW_BRANCHES

UNION ALL

SELECT
    'EMPLOYEES',
    COUNT(*)
FROM RAW_EMPLOYEES

UNION ALL

SELECT
    'CUSTOMERS',
    COUNT(*)
FROM RAW_CUSTOMERS

UNION ALL

SELECT
    'ACCOUNTS',
    COUNT(*)
FROM RAW_ACCOUNTS

UNION ALL

SELECT
    'LOANS',
    COUNT(*)
FROM RAW_LOANS

UNION ALL

SELECT
    'CREDIT_CARDS',
    COUNT(*)
FROM RAW_CREDIT_CARDS

UNION ALL

SELECT
    'TRANSACTIONS',
    COUNT(*)
FROM RAW_TRANSACTIONS

UNION ALL

SELECT
    'FRAUD',
    COUNT(*)
FROM RAW_FRAUD;