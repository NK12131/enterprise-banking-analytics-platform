USE DATABASE ENTERPRISE_BANKING;
USE SCHEMA STAGING;

SELECT
    'BRANCHES' AS DATASET,
    COUNT(*) AS ROW_COUNT
FROM STG_BRANCHES

UNION ALL

SELECT 'EMPLOYEES', COUNT(*)
FROM STG_EMPLOYEES

UNION ALL

SELECT 'CUSTOMERS', COUNT(*)
FROM STG_CUSTOMERS

UNION ALL

SELECT 'ACCOUNTS', COUNT(*)
FROM STG_ACCOUNTS

UNION ALL

SELECT 'LOANS', COUNT(*)
FROM STG_LOANS

UNION ALL

SELECT 'CREDIT_CARDS', COUNT(*)
FROM STG_CREDIT_CARDS

UNION ALL

SELECT 'TRANSACTIONS', COUNT(*)
FROM STG_TRANSACTIONS

UNION ALL

SELECT 'FRAUD', COUNT(*)
FROM STG_FRAUD;